static int wall_at(int x, int y) {
    if (x <= 0 || x >= 15 || y <= 0 || y >= 15) return 1;
    if (x == 4 && y >= 3 && y <= 12 && y != 8) return 1;
    if (x == 11 && y >= 3 && y <= 12 && y != 7) return 1;
    if (y == 4 && x >= 4 && x <= 11 && x != 7) return 1;
    if (y == 11 && x >= 4 && x <= 11 && x != 8) return 1;
    if ((x == 6 && y == 7) || (x == 9 && y == 9)) return 1;
    return 0;
}

void DoomProbe_Render(uint8_t *pixels, uint8_t view_angle) {
    const int origin_x = 8 * 256 + 128;
    const int origin_y = 8 * 256 + 128;
    int x;
    if (!pixels) return;

    for (x = 0; x < DOOM_PROBE_W; ++x) {
        const int offset = ((x - DOOM_PROBE_W / 2) * 42) / (DOOM_PROBE_W / 2);
        const uint8_t angle = (uint8_t)(view_angle + offset);
        const int dx = sine_q14[(uint8_t)(angle + 64)];
        const int dy = sine_q14[angle];
        int rx = origin_x;
        int ry = origin_y;
        int step;
        int hit_x = 0;
        int hit_y = 0;
        int distance;
        int top;
        int bottom;
        int y;

        for (step = 1; step <= 128; ++step) {
            rx += dx >> 10;
            ry += dy >> 10;
            hit_x = rx >> 8;
            hit_y = ry >> 8;
            if (wall_at(hit_x, hit_y)) break;
        }

        distance = (step * 16 * sine_q14[(uint8_t)(offset + 64)]) >> 14;
        if (distance < 64) distance = 64;
        {
            int height = (92 * 256) / distance;
            if (height > DOOM_PROBE_H) height = DOOM_PROBE_H;
            top = (DOOM_PROBE_H - height) / 2;
            bottom = top + height;
        }

        for (y = 0; y < DOOM_PROBE_H; ++y) {
            uint8_t gray;
            if (y < top) {
                gray = (uint8_t)(195 - y / 2);
            } else if (y >= bottom) {
                gray = (uint8_t)(55 + y / 3);
            } else {
                const int texture = ((rx ^ ry ^ (y * 7)) >> 4) & 1;
                gray = (uint8_t)(80 + ((hit_x + hit_y) & 3) * 25 + texture * 30);
            }
            pixels[y * DOOM_PROBE_W + x] = gray;
        }
    }
}
